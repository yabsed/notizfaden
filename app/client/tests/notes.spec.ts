  await page.getByRole('button', { name: '휴지통', exact: true }).click();
  await expect(page.getByText('브라우저 검증 메모', { exact: true })).toBeVisible();
  await page.getByTestId('note-card').hover();
  await page.getByRole('button', { name: '메모 복원', exact: true }).click();
  await expect(page.getByText('휴지통이 비어 있어요')).toBeVisible();
  await page.getByRole('button', { name: '메모', exact: true }).click();
