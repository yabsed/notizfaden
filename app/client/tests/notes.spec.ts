test('offline simultaneous edits keep both versions after reconnect', async ({ page, browser, request }) => {
  const response = await request.post('http://localhost:8081/api/auth/register', { data: { username: 'conflict_' + Date.now(), password: 'teum-conflict-password' } });
  const session = await response.json();
  await page.addInitScript(s => localStorage.setItem('teum-session', JSON.stringify(s)), session);
  await page.goto('/');
  await page.getByRole('button', { name: '메모 작성…', exact: true }).click();
  await page.getByRole('textbox', { name: '메모 제목' }).fill('동시 수정');
  await page.getByRole('textbox', { name: '메모 내용' }).fill('원래 내용');
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await expect(page.locator('.sync-status')).toHaveText('동기화됨');
  const device = await browser.newContext();
  await device.addInitScript(s => localStorage.setItem('teum-session', JSON.stringify(s)), session);
  const offline = await device.newPage(); await offline.goto('/');
  await expect(offline.getByText('원래 내용', { exact: true })).toBeVisible();
  await device.setOffline(true);
  await offline.getByRole('button', { name: '동시 수정 열기', exact: true }).click();
  await offline.getByRole('textbox', { name: '메모 내용' }).fill('오프라인 수정본');
  await offline.getByRole('button', { name: '닫기', exact: true }).click();
  await page.getByRole('button', { name: '동시 수정 열기', exact: true }).click();
  await page.getByRole('textbox', { name: '메모 내용' }).fill('온라인 수정본');
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await expect(page.locator('.sync-status')).toHaveText('동기화됨');
  await device.setOffline(false);
  await expect(offline.getByRole('button', { name: '두 버전 보관' })).toBeVisible();
  await offline.getByRole('button', { name: '두 버전 보관' }).click();
  await expect(offline.getByText('온라인 수정본', { exact: true })).toBeVisible();
  await expect(offline.getByText('오프라인 수정본', { exact: true })).toBeVisible();
  await expect(offline.locator('.sync-status')).toHaveText('동기화됨');
  await device.close();
});
