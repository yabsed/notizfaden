  const card = page.getByTestId('note-card');
  await card.hover();
  await card.getByRole('button', { name: '메모 보관', exact: true }).click();
  await page.getByRole('button', { name: '보관함', exact: true }).click();
  await expect(page.getByText('브라우저 검증 메모', { exact: true })).toBeVisible();
